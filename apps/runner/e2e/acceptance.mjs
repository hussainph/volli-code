/**
 * Publish the CI-built runner as release `v<version>` on the local release:
 * the manifest, stamped installer and checksums are generated by BYO-7's own
 * release script with `--release-base` pointing here, exactly as a release
 * generates them for github.com.
 */
async function publishRunnerRelease(context, assetsDir) {
  const { release } = context;
  const version = assetSetVersion(readdirSync(assetsDir));
  const tag = `v${version}`;
  const staged = mkdtempSync(join(tmpdir(), `byo-release-${version}-`));
  for (const name of readdirSync(assetsDir)) {
    if (/^volli-runner-.+\.tar\.gz(\.sha256)?$/u.test(name)) {
      copyFileSync(join(assetsDir, name), join(staged, name));
    }
  }
  await exec(
    process.execPath,
    [
      join(ROOT, "scripts/runner-release-manifest.mjs"),
      "--assets",
      staged,
      "--release-base",
      release.downloadBase(tag),
    ],
    { cwd: ROOT },
  );
  const assets = Object.fromEntries(readdirSync(staged).map((name) => [name, join(staged, name)]));
  for (const required of [
    "volli-runner-manifest.json",
    "volli-runner-install.sh",
    "volli-runner-SHA256SUMS",
  ]) {
    assert.ok(assets[required], `the release script wrote ${required}`);
  }
  release.publish(tag, assets);
  return { version, tag, base: release.downloadBase(tag) };
}

